import { isAbsolute } from 'node:path';
const baseURL = process.env.LANDI_WORKSPACE_BASE_URL;
if (process.env.LANDI_BOOKING_IMPACT_E2E !== '1') throw new Error('须显式启用预订关系专项');
if (!baseURL) throw new Error('须指定自有隔离实例地址');
